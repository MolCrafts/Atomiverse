#!/usr/bin/env bash
# Regenerate every LAMMPS reference of the units-parity data from the decks.
#
#   LMP=/path/to/lmp tests/data/lammps_units/make_refs.sh
#
# Serial, one OpenMP thread. Per case writes ref.<case>.dump (LAMMPS dump,
# %.17g, sorted by id) and ref.<case>.thermo (the thermo table of the run:
# header row + one row per output step, %.17g, thermo_modify norm no), then
# defaults.txt (LAMMPS default timestep and neighbor skin per units style).
set -euo pipefail
LMP=${LMP:-lmp}
here=$(cd "$(dirname "$0")" && pwd)
export OMP_NUM_THREADS=1
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

thermo_table() { # log -> header + rows between "Step" and "Loop time"
    awk '/^ *Step /{on=1} /^Loop time/{on=0} on' "$1" | sed 's/[[:space:]]*$//'
}

for style in lj real metal si electron; do
    for deck in "$here/$style"/in.*.lmp; do
        case=$(basename "$deck" .lmp); case=${case#in.}
        (cd "$here/$style" && "$LMP" -in "$deck" -log "$tmp/log" -screen none)
        thermo_table "$tmp/log" > "$here/$style/ref.$case.thermo"
        echo "$style/$case"
    done
done

# Defaults LAMMPS sets with `units <style>` (Update::set_units): the timestep
# from `dt`, the skin as the master neighbor cutoff minus the pair cutoff.
{
    echo "# style dt skin  (LAMMPS defaults after 'units <style>'; generated by make_refs.sh)"
    for style in lj real metal si cgs electron micro nano; do
        cat > "$tmp/in.defaults" <<EOI
units $style
atom_style atomic
region box block 0 10 0 10 0 10
create_box 1 box
create_atoms 1 single 5 5 5
mass 1 1.0
pair_style zero 1.0
pair_coeff * *
variable d equal dt
run 0
print "DEFAULT_DT \${d}"
EOI
        (cd "$tmp" && "$LMP" -in in.defaults -log "$tmp/log.d" -screen none)
        dt=$(awk '/^DEFAULT_DT/{print $2}' "$tmp/log.d")
        master=$(awk '/master list distance cutoff/{print $NF}' "$tmp/log.d")
        skin=$(awk -v m="$master" 'BEGIN{printf "%.10g", m - 1.0}')
        echo "$style $dt $skin"
    done
} > "$here/defaults.txt"
echo defaults
