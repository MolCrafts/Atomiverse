/// @file cpu/observe/voronoi_volume.h
/// @brief Periodic Voronoi cell volumes — Thomas–Fermi site-volume companion.
///
/// MetalWalls' Thomas–Fermi electrode metallicity (Scalfi et al., J. Chem.
/// Phys. 153, 174704 (2020)) takes a per-species `voronoi_volume` next to
/// `thomas_fermi_length`: the TF hardness is
/// \(A_{ii}\mathrel{+}= 4\pi k_e l_{\mathrm{TF}}^2 / v_i\) with \(v_i\) the
/// Voronoi volume of the electrode site. `VoronoiVolume` computes those
/// volumes from geometry (typically on a bulk electrode crystal frame);
/// the result feeds `cpu::md::ConstPotBO::site_volume`.
///
/// Setup-time companion — a plain domain type, not a hot-path Component.
#pragma once

#include <vector>

namespace ATV {
namespace cpu {

class Frame;

/// @brief Periodic Voronoi tessellation volumes for orthorhombic cells.
///
/// The tessellation is generated by **all** atoms in the frame (min-imaged),
/// so \(\sum_i v_i = V_{\mathrm{box}}\) exactly. Each cell is computed by
/// convex bisector clipping: the initial cell is the box cuboid centred on
/// the site (the self-image bisectors of an orthorhombic lattice), clipped
/// by the perpendicular-bisector half-spaces of every neighbor image that
/// can reach the cell, nearest first.
///
/// @code
/// cpu::VoronoiVolume vv;
/// std::vector<double> v = vv.volumes(bulk_gold);   // [Å³] per frame row
/// conp.site_volume = v;                            // TF companion
/// @endcode
class VoronoiVolume {
  public:
    VoronoiVolume() = default;

    /// @brief Voronoi cell volume of every atom in `frame`.
    /// @param frame System snapshot; positions [Å], orthorhombic box.
    /// @return Per-row cell volumes [Å³] (size = frame nlocal); their sum
    ///         equals the box volume.
    /// @throws std::invalid_argument on an empty frame, a non-orthorhombic
    ///         box, or a degenerate (non-positive) box edge.
    /// @throws std::runtime_error on coincident sites (separation < 1e-6 Å).
    std::vector<double> volumes(const Frame& frame) const;
};

} // namespace cpu
} // namespace ATV
