#!/usr/bin/env python
"""Emit an Atomiverse basis_data/*.h static table from PySCF's basis library.

Usage (run manually inside the oracle venv — NEVER wired into CMake/ctest):

    python tools/gen_basis_data.py <pyscf-basis-name> <header-stem> <El> [El ...]
    python tools/gen_basis_data.py --check <header-path> <pyscf-basis-name> \
        <header-stem> <El> [El ...]

Examples:

    python tools/gen_basis_data.py sto-3g sto3g H He Li Be B C N O > \
        include/atomiverse/cpu/scf/basis_data/sto3g.h
    python tools/gen_basis_data.py --check \
        include/atomiverse/cpu/scf/basis_data/sto3g.h sto-3g sto3g H He Li Be B C N O

Registered sets (SETS below) map the PySCF basis name to the header stem and
the canonical element list, so the stem/element arguments may be omitted:

    python tools/gen_basis_data.py 6-31+g* > \
        include/atomiverse/cpu/scf/basis_data/pople_631pgs.h
    python tools/gen_basis_data.py --check \
        include/atomiverse/cpu/scf/basis_data/aug_ccpvdz.h aug-cc-pvdz

Effective core potentials (`--ecp`, registry ECP_SETS) emit an AtomEcp table
from PySCF's `gto.basis.load_ecp` instead of an AtomBasis table:

    python tools/gen_basis_data.py --ecp def2-svp > \
        include/atomiverse/cpu/scf/basis_data/ecp_def2.h
    python tools/gen_basis_data.py --check \
        include/atomiverse/cpu/scf/basis_data/ecp_def2.h --ecp def2-svp

The emitted header still records the fully explicit Regenerate command.

The emitted numbers come from `pyscf.gto.M(...)._basis` — the raw,
UNNORMALIZED contraction convention (physical GTO normalization is applied
by the C++ ShellList constructor). Output is byte-deterministic: identical
inputs produce identical bytes, and `--check` exits non-zero with a unified
diff when the target header does not match the regenerated text.

Unsupported elements (not present in the requested list, or absent from the
PySCF basis library for the requested basis) raise a hard error — no
fallback, per the repository's no-fallback rule.
"""

import sys

L_LETTER = "spdfgh"

# Periodic table symbols indexed by Z (enough for the basis_data tables).
SYMBOLS = [
    "X", "H", "He", "Li", "Be", "B", "C", "N", "O", "F", "Ne",
    "Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar", "K", "Ca",
    "Sc", "Ti", "V", "Cr", "Mn", "Fe", "Co", "Ni", "Cu", "Zn",
    "Ga", "Ge", "As", "Se", "Br", "Kr", "Rb", "Sr", "Y", "Zr",
    "Nb", "Mo", "Tc", "Ru", "Rh", "Pd", "Ag", "Cd", "In", "Sn",
    "Sb", "Te", "I", "Xe", "Cs", "Ba", "La", "Ce", "Pr", "Nd",
    "Pm", "Sm", "Eu", "Gd", "Tb", "Dy", "Ho", "Er", "Tm", "Yb",
    "Lu", "Hf", "Ta", "W", "Re", "Os", "Ir", "Pt", "Au", "Hg",
    "Tl", "Pb", "Bi", "Po", "At", "Rn",
]
Z_OF = {sym: z for z, sym in enumerate(SYMBOLS)}

# Third-period block shared by every registered set (Z=11–18, Na–Ar).
PERIOD3 = ["Na", "Mg", "Al", "Si", "P", "S", "Cl", "Ar"]

# def2-ECP heavy-element block (Weigend-Ahlrichs 2005): Rb–La and Hf–Rn.
# The lanthanides Ce–Lu are NOT part of the def2 family (PySCF has no
# def2-svp rows for them) and stay absent — no fallback.
HEAVY_DEF2 = [
    "Rb", "Sr", "Y", "Zr", "Nb", "Mo", "Tc", "Ru", "Rh", "Pd", "Ag", "Cd",
    "In", "Sn", "Sb", "Te", "I", "Xe", "Cs", "Ba", "La",
    "Hf", "Ta", "W", "Re", "Os", "Ir", "Pt", "Au", "Hg",
    "Tl", "Pb", "Bi", "Po", "At", "Rn",
]

# Registered sets: PySCF basis name -> (header stem, canonical element list).
# Pople sets carry K/Ca as well (defined in PySCF's 6-31G family tables);
# def2-tzvp / aug-cc sets stop at Ar (K/Ca would need the ECP-free
# large-core route — out of scope). def2-svp additionally carries the
# def2-ECP heavy-element valence rows Rb–Rn (paired with ecp_def2 below).
# STO-3G is deliberately NOT registered: that table is frozen and never
# regenerated by the short form.
SETS = {
    "6-31g": ("pople_631g", ["H", "He", "C", "N", "O", "F"] + PERIOD3 + ["K", "Ca"]),
    "6-31g*": ("pople_631gs", ["H", "C", "N", "O", "F"] + PERIOD3 + ["K", "Ca"]),
    "6-31+g*": ("pople_631pgs", ["H", "C", "N", "O", "F"] + PERIOD3 + ["K", "Ca"]),
    "def2-svp": ("def2_svp", ["H", "C", "N", "O", "F"] + PERIOD3 + HEAVY_DEF2),
    "def2-tzvp": ("def2_tzvp", ["H", "C", "N", "O", "F"] + PERIOD3),
    "aug-cc-pvdz": ("aug_ccpvdz", ["H", "C", "N", "O", "F"] + PERIOD3),
    # def2 universal JKFIT auxiliary basis (Weigend 2002, DOI
    # 10.1039/B204199P). Coverage mirrors the light-element orbital def2
    # sets: H + first/second row (max l = 4, g). The heavy def2 elements
    # (Rb-Rn) carry h/i JKFIT shells (l >= 5) beyond the engine's l = 4
    # cap and are deliberately not emitted — no fallback, the aux
    # ShellList constructor throws for them.
    "def2-universal-jkfit": ("def2_jkfit", ["H", "C", "N", "O", "F"] + PERIOD3),
}

# Extra per-stem Doxygen note lines inserted into the emitted header
# (deterministic — part of the byte-reproducible output).
EXTRA_NOTES = {
    "def2_jkfit": [
        "///",
        "/// Density-fitting AUXILIARY basis (not an orbital basis).",
        "/// Single-table decision: only the universal JKFIT set is shipped,",
        "/// deliberately without a separate JFIT table — the exchange fit",
        "/// (RI-K) REQUIRES the larger JKFIT set (Weigend, PCCP 4, 4285",
        "/// (2002), DOI 10.1039/B204199P), and reusing JKFIT for the Coulomb",
        "/// fit (RI-J) only costs a slightly larger auxiliary dimension at",
        "/// unchanged accuracy (Weigend, PCCP 8, 1057 (2006), DOI",
        "/// 10.1039/b515623h). Robust-fit background: Vahtras, Almlof,",
        "/// Feyereisen, CPL 213, 514 (1993), DOI 10.1016/0009-2614(93)89151-7.",
        "/// Rows include l = 4 (g) shells; heavy def2 elements (Rb-Rn) need",
        "/// l >= 5 and are not emitted (aux ShellList throws, no fallback).",
    ],
}

# Registered ECP sets: PySCF ECP name -> (header stem, canonical elements).
ECP_SETS = {
    "def2-svp": ("ecp_def2", list(HEAVY_DEF2)),
}

WIDTH = 80


def fetch_basis(basis_name, symbols):
    """Return {symbol: [[l, [e, c], ...], ...]} from PySCF's basis library."""
    from pyscf import gto

    out = {}
    for sym in symbols:
        raw = gto.basis.load(basis_name, sym)
        if not raw:
            raise SystemExit(
                f"error: element {sym} not defined in PySCF basis "
                f"'{basis_name}' — no fallback"
            )
        out[sym] = raw
    return out


def num(x):
    """Shortest exact decimal for a float (Python repr convention)."""
    return repr(float(x))


def wrap_list(values, first_indent, cont_indent):
    """Render {a, b, c} wrapped at WIDTH columns.

    `first_indent` is the column where the opening brace sits; continuation
    lines are indented with `cont_indent` spaces (one past the brace).
    """
    parts = [num(v) for v in values]
    lines = []
    cur = "{"
    col = first_indent + 1
    for i, p in enumerate(parts):
        piece = p + (", " if i < len(parts) - 1 else "")
        if col + len(piece.rstrip()) > WIDTH and cur != "{":
            lines.append(cur.rstrip())
            cur = " " * cont_indent
            col = cont_indent
        cur += piece
        col += len(piece)
    cur += "}"
    lines.append(cur)
    return lines


def render_shell(l, exps, coeffs):
    """Correct multi-line renderer (used instead of shell_lines tail hack)."""
    letter = L_LETTER[l]
    head = f"                ContractedShell{{/*l=*/{l} /* {letter} */,"
    one = (
        head
        + " {"
        + ", ".join(num(e) for e in exps)
        + "}, {"
        + ", ".join(num(c) for c in coeffs)
        + "}},"
    )
    if len(one) <= WIDTH:
        return [one]
    ind = 32
    out = [head]
    e_lines = wrap_list(exps, ind, ind + 1)
    e_lines[0] = " " * ind + e_lines[0]
    e_lines[-1] += ","
    out.extend(e_lines)
    c_lines = wrap_list(coeffs, ind, ind + 1)
    c_lines[0] = " " * ind + c_lines[0]
    c_lines[-1] += "},"
    out.extend(c_lines)
    return out


def render(basis_name, stem, symbols):
    zs = []
    for sym in symbols:
        if sym not in Z_OF:
            raise SystemExit(f"error: unknown element symbol '{sym}'")
        zs.append(Z_OF[sym])
    order = sorted(zip(zs, symbols))
    max_z = order[-1][0]
    by_z = dict(order)

    data = fetch_basis(basis_name, [s for _, s in order])

    syms_comma = ", ".join(s for _, s in order)
    syms_space = " ".join(s for _, s in order)

    lines = []
    a = lines.append
    a(f"/// @file cpu/scf/basis_data/{stem}.h")
    a(f"/// @brief {basis_name} basis-set table (auto-generated; do not edit).")
    a("///")
    a("/// Emitted by `tools/gen_basis_data.py` from PySCF's `mol._basis`")
    a("/// dictionary, so numerical values match the PySCF ground-truth path")
    a("/// bit-for-bit. Contraction coefficients use the unnormalized")
    a("/// convention (physical GTO normalization is applied by")
    a("/// `ShellList` constructor).")
    for note in EXTRA_NOTES.get(stem, []):
        a(note)
    a("///")
    a(f"/// Supported elements: {syms_comma}.")
    a("///")
    a("/// Regenerate:")
    a(f"///   python tools/gen_basis_data.py {basis_name} {stem} {syms_space}")
    a("#pragma once")
    a("")
    a("#include <vector>")
    a("")
    a('#include "atomiverse/cpu/scf/basis_data/basis_table.h"')
    a("")
    a("namespace ATV {")
    a("namespace cpu {")
    a("namespace scf {")
    a("namespace basis_data {")
    a("")
    a(f"/// @brief Get the {basis_name} table, indexed by atomic number Z.")
    a("/// @return Reference to a static table with AtomBasis entries for")
    a(f"///         Z=1..{max_z}; position 0 and any unsupported Z are empty.")
    a(f"inline const std::vector<AtomBasis>& {stem}() {{")
    a("    static const std::vector<AtomBasis> data = []() {")
    a("        return std::vector<AtomBasis>{")
    a("            AtomBasis{}, // Z=0 unused")
    for z in range(1, max_z + 1):
        if z not in by_z:
            a(f"            AtomBasis{{}}, // Z={z} unsupported")
            continue
        sym = by_z[z]
        shells = data[sym]
        # General contractions (multiple coefficient columns sharing one
        # primitive set, e.g. the cc-pVDZ s block) are split into one
        # ContractedShell per column — the spanned AO space is identical
        # and column order follows PySCF's nctr ordering.
        split = []
        for shell in shells:
            l = shell[0]
            prims = shell[1:]
            exps = [p[0] for p in prims]
            n_cols = len(prims[0]) - 1
            for col in range(1, n_cols + 1):
                split.append((l, exps, [p[col] for p in prims]))
        a(f"            // Z={z} ({sym}): {len(split)} shells")
        a("            AtomBasis{{")
        for l, exps, coeffs in split:
            lines.extend(render_shell(l, exps, coeffs))
        a("            }},")
    a("        };")
    a("    }();")
    a("    return data;")
    a("}")
    a("")
    a("} // namespace basis_data")
    a("} // namespace scf")
    a("} // namespace cpu")
    a("} // namespace ATV")
    return "\n".join(lines) + "\n"


def fetch_ecp(ecp_name, symbols):
    """Return {symbol: (n_core, channels)} from PySCF's ECP library.

    `channels` is the raw PySCF list [[l, by_r_power], ...] where l == -1
    marks the local part U_L and the by_r_power list index k groups the
    Gaussian terms d * r^(k-2) * exp(-alpha r^2).
    """
    from pyscf import gto

    out = {}
    for sym in symbols:
        raw = gto.basis.load_ecp(ecp_name, sym)
        if not raw:
            raise SystemExit(
                f"error: element {sym} not defined in PySCF ECP "
                f"'{ecp_name}' — no fallback"
            )
        out[sym] = raw
    return out


def render_ecp(ecp_name, stem, symbols):
    zs = []
    for sym in symbols:
        if sym not in Z_OF:
            raise SystemExit(f"error: unknown element symbol '{sym}'")
        zs.append(Z_OF[sym])
    order = sorted(zip(zs, symbols))
    max_z = order[-1][0]
    by_z = dict(order)

    data = fetch_ecp(ecp_name, [s for _, s in order])

    syms_comma = ", ".join(s for _, s in order)

    lines = []
    a = lines.append
    a(f"/// @file cpu/scf/basis_data/{stem}.h")
    a(f"/// @brief {ecp_name} effective-core-potential table (auto-generated;")
    a("///        do not edit).")
    a("///")
    a("/// Emitted by `tools/gen_basis_data.py` from PySCF's")
    a(f"/// `gto.basis.load_ecp(\"{ecp_name}\", El)` data, so numerical values")
    a("/// match the PySCF ground-truth path bit-for-bit. Channel storage")
    a("/// follows the PySCF/def2 convention: projector channels hold")
    a("/// U_l - U_L; the LAST channel of each AtomEcp is the local part U_L")
    a("/// (PySCF l = -1, relabeled to l = L = 1 + max projector l).")
    a("/// Exponents/coefficients in atomic units (Bohr^-2 / Hartree).")
    a("///")
    a(f"/// Supported elements: {syms_comma}.")
    a("/// All other Z (def2 convention: Z <= 36) are all-electron — their")
    a("/// rows are empty AtomEcp entries.")
    a("///")
    a("/// Regenerate:")
    a(f"///   python tools/gen_basis_data.py --ecp {ecp_name}")
    a("#pragma once")
    a("")
    a("#include <vector>")
    a("")
    a('#include "atomiverse/cpu/scf/basis_data/basis_table.h"')
    a("")
    a("namespace ATV {")
    a("namespace cpu {")
    a("namespace scf {")
    a("namespace basis_data {")
    a("")
    a(f"/// @brief Get the {ecp_name} ECP table, indexed by atomic number Z.")
    a("/// @return Reference to a static table with AtomEcp entries for")
    a(f"///         Z=1..{max_z}; position 0 and any all-electron Z are empty.")
    a(f"inline const std::vector<AtomEcp>& {stem}() {{")
    a("    static const std::vector<AtomEcp> data = []() {")
    a("        return std::vector<AtomEcp>{")
    a("            AtomEcp{}, // Z=0 unused")
    for z in range(1, max_z + 1):
        if z not in by_z:
            a(f"            AtomEcp{{}}, // Z={z} all-electron")
            continue
        sym = by_z[z]
        n_core, raw_channels = data[sym]
        local = None
        projs = []
        for l, by_power in raw_channels:
            terms = []
            for power, group in enumerate(by_power):
                for exp_c in group:
                    terms.append((power, exp_c[0], exp_c[1]))
            if l == -1:
                local = terms
            else:
                projs.append((l, terms))
        if local is None:
            raise SystemExit(
                f"error: {ecp_name}/{sym} has no local (l=-1) channel — "
                "the AtomEcp convention requires U_L last"
            )
        projs.sort(key=lambda ch: ch[0])
        l_local = projs[-1][0] + 1 if projs else 0
        channels = projs + [(l_local, local)]
        n_proj = len(projs)
        a(f"            // Z={z} ({sym}): n_core={n_core}, "
          f"{n_proj} projector channels + local")
        a(f"            AtomEcp{{{n_core}, {{")
        for ci, (l, terms) in enumerate(channels):
            tag = " // local U_L" if ci == len(channels) - 1 else ""
            a(f"                EcpChannel{{{l}, {{{tag}")
            for n_pow, e, c in terms:
                a("                    "
                  f"EcpGaussianTerm{{{n_pow}, {num(e)}, {num(c)}}},")
            a("                }},")
        a("            }},")
    a("        };")
    a("    }();")
    a("    return data;")
    a("}")
    a("")
    a("} // namespace basis_data")
    a("} // namespace scf")
    a("} // namespace cpu")
    a("} // namespace ATV")
    return "\n".join(lines) + "\n"


def resolve_set(basis_name, rest):
    """Return (stem, symbols) from explicit args or the SETS registry."""
    if rest:
        return rest[0], rest[1:]
    if basis_name not in SETS:
        raise SystemExit(
            f"error: basis '{basis_name}' not in the SETS registry — pass "
            f"<header-stem> <El> [El ...] explicitly"
        )
    stem, symbols = SETS[basis_name]
    return stem, list(symbols)


def resolve_ecp_set(ecp_name, rest):
    """Return (stem, symbols) from explicit args or the ECP_SETS registry."""
    if rest:
        return rest[0], rest[1:]
    if ecp_name not in ECP_SETS:
        raise SystemExit(
            f"error: ECP '{ecp_name}' not in the ECP_SETS registry — pass "
            f"<header-stem> <El> [El ...] explicitly"
        )
    stem, symbols = ECP_SETS[ecp_name]
    return stem, list(symbols)


def render_args(args):
    """Render from post-`--check` style args: [--ecp] <name> [stem El ...]."""
    if args and args[0] == "--ecp":
        if len(args) < 2:
            raise SystemExit(__doc__)
        stem, symbols = resolve_ecp_set(args[1], args[2:])
        if not symbols:
            raise SystemExit(__doc__)
        return render_ecp(args[1], stem, symbols)
    if not args:
        raise SystemExit(__doc__)
    stem, symbols = resolve_set(args[0], args[1:])
    if not symbols:
        raise SystemExit(__doc__)
    return render(args[0], stem, symbols)


def main(argv):
    if len(argv) >= 2 and argv[1] == "--check":
        if len(argv) < 4:
            raise SystemExit(__doc__)
        path = argv[2]
        text = render_args(argv[3:])
        with open(path, encoding="utf-8") as fh:
            on_disk = fh.read()
        if text == on_disk:
            print(f"OK: {path} is byte-identical to regenerated output")
            return 0
        import difflib

        diff = difflib.unified_diff(
            on_disk.splitlines(keepends=True),
            text.splitlines(keepends=True),
            fromfile=path,
            tofile="regenerated",
        )
        sys.stdout.writelines(diff)
        print(f"MISMATCH: {path} differs from regenerated output")
        return 1

    if len(argv) < 2:
        raise SystemExit(__doc__)
    sys.stdout.write(render_args(argv[1:]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
