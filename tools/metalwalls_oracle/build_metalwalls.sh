#!/bin/bash -l
# Build the MetalWalls oracle binary on the Arrhenius x86_64 login node.
#
# MetalWalls is an OFFLINE oracle: ctest never launches it. This script only
# has to be re-run when the pin source needs refreshing or the toolchain moves.
#
#   Upstream: https://gitlab.com/ampere2/metalwalls (release branch)
#   Reference: Marin-Laflèche et al., J. Open Source Softw. 5, 2373 (2020),
#              DOI 10.21105/joss.02373
#
# Usage:  bash -l tools/metalwalls_oracle/build_metalwalls.sh [install_root]
#
# Produces $MW_ROOT/mw (MPI Fortran executable).

set -euo pipefail

MW_ROOT="${1:-/nobackup/proj/disk/teoroo/personal/jicli594/work/opt/metalwalls}"

# Lmod defines `module` as a shell function — never pipe `module load`, a
# subshell loses the environment (this is the #1 build failure here).
module load buildenv-gcc/2026.03-mpich
export LD_LIBRARY_PATH="$LIBRARY_PATH:$LD_LIBRARY_PATH"

if [ ! -d "$MW_ROOT/.git" ]; then
    mkdir -p "$(dirname "$MW_ROOT")"
    git clone https://gitlab.com/ampere2/metalwalls.git "$MW_ROOT"
fi

cd "$MW_ROOT"

# MetalWalls needs only a Fortran compiler + LAPACK (OpenBLAS supplies it).
cat > config.mk <<CFG
# Generated by tools/metalwalls_oracle/build_metalwalls.sh
F90 := mpif90
F90FLAGS := -O2 -march=native -mtune=native -ftree-vectorize -ffree-line-length-none
FPPFLAGS := -cpp
LDFLAGS := -L$OPENBLASDIR/lib -lopenblas
J := -J
CFG

make clean >/dev/null 2>&1 || true
make -j"$(nproc)"

echo "built: $MW_ROOT/mw  (git $(git rev-parse --short HEAD))"

# Self-check against an upstream reference case (MaZe + electrodes, ~7 s).
VERIFY=/tmp/mw_oracle_selfcheck
rm -rf "$VERIFY" && mkdir -p "$VERIFY"
cp tests/maze/electrodes/LiCl-Al/{runtime.inpt,data.inpt} "$VERIFY/"
( cd "$VERIFY" && mpirun -n 1 "$MW_ROOT/mw" > run.stdout 2>&1 )
python3 - "$VERIFY/energies.out" "$MW_ROOT/tests/maze/electrodes/LiCl-Al/energies.ref" <<'PY'
import sys
def last(path):
    with open(path) as fh:
        rows = [l.split() for l in fh if not l.startswith('#') and l.strip()]
    return float(rows[-1][1])
got, ref = last(sys.argv[1]), last(sys.argv[2])
rel = abs(got - ref) / abs(ref)
print(f"self-check Hamiltonian: {got:.15e} vs ref {ref:.15e}  rel={rel:.2e}")
assert rel < 1e-9, "MetalWalls self-check FAILED — do not pin from this build"
print("self-check PASS")
PY
