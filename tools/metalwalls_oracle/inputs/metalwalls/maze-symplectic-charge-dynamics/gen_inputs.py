#!/usr/bin/env python3
"""Generate MetalWalls twins of the Atomiverse regression
``regressions/md/maze-symplectic-charge-dynamics``.

The Atomiverse regression simulates a 10-atom parallel-plate capacitor with
*minimum-image* real-space Coulomb (``PairGaussianCoul``, cutoff 12 A, and
``ConstPotBO::xy_image_range = 0`` for the elastance).  MetalWalls has no
minimum-image Coulomb mode: its electrostatics is always Ewald-summed
(``num_pbc`` 2 or 3).  Two twins are therefore generated:

* ``twinA_ewald_6x6x20`` -- the regression geometry verbatim, but with
  MetalWalls' 3D Ewald.  This is the "same box" twin; it quantifies how far
  the regression's minimum-image truncation sits from the fully periodic
  answer for that box.
* ``twinB_dilute_<L>`` -- the identical 10-atom cluster in a large cubic box.
  As L grows the Ewald sum converges to the bare (isolated) pairwise
  Gaussian-Coulomb sum, which is *exactly* the model Atomiverse evaluates in
  minimum image when the cutoff exceeds the cluster diameter.  This twin is
  the kernel-matched, apples-to-apples ATV<->MW comparison.

Units.  Atomiverse public surface: eV, Angstrom, fs, amu, V, e.
MetalWalls input/output: Hartree atomic units -- Bohr, Hartree, e, and the
electric potential in Eh/e; the timestep in atomic time units.

    1 Bohr  = 0.529177210903 A
    1 Ha    = 27.211386245988 eV
    1 fs    = 41.341373335182 a.u. of time
    1 Ha/e  = 27.211386245988 V
    eta [1/Bohr] = eta [1/A] * 0.529177210903      (eta is an inverse length)

MetalWalls' own bohr2angstrom (src/constants.F90) is 0.52917721067, which
differs from the CODATA-2018 value used here by 4.4e-10 relative -- five
orders of magnitude below any tolerance in play.
"""

import os

BOHR_A = 0.529177210903  # A per Bohr
HARTREE_EV = 27.211386245988  # eV per Ha
FS_AU = 41.341373335182  # a.u. of time per fs


def A2B(x):
    return x / BOHR_A


# ---------------------------------------------------------------- ATV system
LXY = 6.0  # [A]
LZ = 20.0  # [A]
ETA_A = 2.0  # [1/A]
PSI_BOT_V = 0.0  # [V]
PSI_TOP_V = 1.0  # [V]
DT_FS = 0.25  # [fs]
M_ION = 40.0  # [amu]
M_WALL = 196.97  # [amu]

# Row order matches the regression's make_capacitor(): bottom plate (iy outer,
# ix inner), then top plate, then the two ions.
PLATE_XY = [(1.5, 1.5), (4.5, 1.5), (1.5, 4.5), (4.5, 4.5)]  # [A]
Z_BOT, Z_TOP = 4.0, 16.0  # [A]
ION = [
    (2.1, 2.1, 8.5, +0.5),  # [A], [e]
    (4.2, 4.2, 11.5, -0.5),
]

ETA_B = ETA_A * BOHR_A  # [1/Bohr]
PSI_BOT_AU = PSI_BOT_V / HARTREE_EV  # [Eh/e]
PSI_TOP_AU = PSI_TOP_V / HARTREE_EV  # [Eh/e]
DT_AU = DT_FS * FS_AU  # [a.u.]


def data_inpt(lx, ly, lz, with_velocities, charge_history=0):
    """MetalWalls data.inpt. Electrode species must come last.

    ``charge_history`` writes N ``# charges`` sections of zeros: MetalWalls'
    MaZe solver refuses to start without at least two stored charge steps
    (its Verlet extrapolation history).  Zero history is the cold bootstrap;
    the constant-potential constraint is linear, so the exact ``inversion``
    correction lands on the constraint surface from any guess.
    """
    lines = [
        "# header",
        "step                             0",
        "num_atoms                       10",
        "num_electrode_atoms              8",
        "# box",
        " %.15E %.15E %.15E" % (A2B(lx), A2B(ly), A2B(lz)),
        "# coordinates :       10 atoms   - step        0",
    ]
    order = []
    for x, y, z, _q in ION:
        order.append(("Ip" if _q > 0 else "Im", x, y, z))
    for x, y in PLATE_XY:
        order.append(("E1", x, y, Z_BOT))
    for x, y in PLATE_XY:
        order.append(("E2", x, y, Z_TOP))
    for name, x, y, z in order:
        lines.append(
            "%-4s %22.15E %22.15E %22.15E" % (name, A2B(x), A2B(y), A2B(z))
        )
    if with_velocities:
        lines.append("# velocities :       10 atoms   - step        0")
        for name, _x, _y, _z in order:
            lines.append(
                "%-4s %22.15E %22.15E %22.15E" % (name, 0.0, 0.0, 0.0)
            )
    for k in range(charge_history):
        lines.append("# charges :        8 atoms   - step %8d" % (k - 1))
        for name, _x, _y, _z in order[2:]:
            lines.append("%-4s %22.15E" % (name, 0.0))
    return "\n".join(lines) + "\n"


def runtime_inpt(lx, ly, lz, num_pbc, num_steps, rcut_A, label,
                 solver="maze inversion 1.0e-14"):
    return f"""# MetalWalls twin of Atomiverse regression maze-symplectic-charge-dynamics
# {label}
# Generated by gen_inputs.py -- all values are atomic units.
# ATV source values: box {lx} x {ly} x {lz} A, eta {ETA_A} 1/A,
# Psi_bot {PSI_BOT_V} V, Psi_top {PSI_TOP_V} V, dt {DT_FS} fs, ions {M_ION} amu.

num_steps {num_steps}
timestep  {DT_AU:.12f}          # {DT_FS} fs
temperature 300.0            # only sets MW's kinetic sanity threshold; v(0)=0

num_pbc  {num_pbc}
box
  length {A2B(lx):.15f} {A2B(ly):.15f} {A2B(lz):.15f}

species

  species_type
    name       Ip
    count      1
    charge point  +0.5
    mass   {M_ION}

  species_type
    name       Im
    count      1
    charge point  -0.5
    mass   {M_ION}

  species_type
    name       E1
    count      4
    charge gaussian {ETA_B:.15f} 0.0
    mass   {M_WALL}
    mobile False

  species_type
    name       E2
    count      4
    charge gaussian {ETA_B:.15f} 0.0
    mass   {M_WALL}
    mobile False

electrodes

  electrode_type
    name       E1
    species    E1
    potential  {PSI_BOT_AU:.15f}      # {PSI_BOT_V} V

  electrode_type
    name       E2
    species    E2
    potential  {PSI_TOP_AU:.15f}      # {PSI_TOP_V} V

  electrode_charges {solver}
  charge_neutrality true electrodes
  compute_force true

interactions
  coulomb
    coulomb_rtol       1.0e-12
    coulomb_rcut       {A2B(rcut_A):.12f}
    coulomb_ktol       1.0e-12

output
  step 1
  charges 1
  forces 1
  energies 1 Hamiltonian Kinetic Potential Coulomb Coulomb_lr Coulomb_keq0 Coulomb_sr Coulomb_self
"""


def write_case(dirname, lx, ly, lz, num_pbc, num_steps, rcut_A, label, vel,
               solver="maze inversion 1.0e-14", charge_history=2):
    here = os.path.dirname(os.path.abspath(__file__))
    d = os.path.join(here, dirname)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "data.inpt"), "w") as fh:
        fh.write(data_inpt(lx, ly, lz, vel, charge_history))
    with open(os.path.join(d, "runtime.inpt"), "w") as fh:
        fh.write(runtime_inpt(lx, ly, lz, num_pbc, num_steps, rcut_A, label,
                              solver))
    print("wrote", d)


if __name__ == "__main__":
    # A: regression geometry, MetalWalls' own 3D Ewald. rcut < L/2 = 3 A.
    write_case("twinA_ewald_6x6x20", LXY, LXY, LZ, 3, 0, 2.9,
               "twin A: regression box, MW 3D Ewald, single charge solve",
               vel=True)
    write_case("twinA_ewald_6x6x20_md", LXY, LXY, LZ, 3, 800, 2.9,
               "twin A: regression box, MW 3D Ewald, 800-step NVE",
               vel=True)
    # B: identical cluster, dilute box -> Ewald converges to the isolated
    #    pairwise sum, i.e. exactly what ATV evaluates in minimum image.
    for L in (40.0, 60.0, 100.0):
        write_case("twinB_dilute_%g" % L, L, L, L, 3, 0, 19.0,
                   "twin B: dilute cluster L=%g A, kernel-matched to ATV" % L,
                   vel=True)
    # B': dense-matrix Born-Oppenheimer solve of the same dilute cluster --
    #     MaZe's converged charges must equal it (linear constraint).
    write_case("twinB_dilute_60_inv", 60.0, 60.0, 60.0, 3, 0, 19.0,
               "twin B': dilute cluster L=60 A, MW matrix_inversion",
               vel=True, solver="matrix_inversion 1.0e-14",
               charge_history=0)
    print("eta   [1/Bohr] = %.15f" % ETA_B)
    print("Psi_top [Eh/e] = %.15f" % PSI_TOP_AU)
    print("dt        [au] = %.12f" % DT_AU)
