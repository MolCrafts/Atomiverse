#!/usr/bin/env python3
"""Generate MetalWalls twins for regressions/md/pim-npt-polarizable-il.

Two twin families are emitted:

  lattice64/{pol,nopol}   the EXACT regression start configuration
                          (4x4x4 rock-salt toy polarizable IL, d = 2.35 A,
                          L = 9.4 A, +1 cation alpha=0 / -1 anion alpha=3 A^3)
                          run under MetalWalls' own PIM Hamiltonian
                          (Ewald, NO Thole damping -- MW has none).
                          E_pol^MW = E_pot(pol) - E_pot(nopol).

  dimer_L<NN>/{pol,nopol} a +1(alpha=0) / -1(alpha=3 A^3) pair at d = 2.35 A
                          in a cubic box of side <NN> Bohr.  As L grows the
                          Ewald images die off as 1/L^3 and the MW answer must
                          converge on the exact isolated-pair polarization
                          energy  E_pol = -1/2 k alpha / d^4, which is the very
                          same charge-dipole kernel ATV's PimInducedDipole
                          uses.  This is the ATV-vs-MW *form* check.

Units: MetalWalls is atomic units throughout (Bohr, Hartree, e, Bohr^3 for
polarizability).  ATV public units are A / eV / e / A^3.

Offline provenance script -- never run at build/ctest/regression time.
"""

import math
import os

BOHR = 0.529177210903          # A per Bohr (CODATA 2018)
HARTREE = 27.211386245988      # eV per Hartree

# ---- regression start configuration (mirrors reg_pim-npt-polarizable-il.cpp)
NC = 4
D_PIN = 2.35                   # A   (pin leg)
D_NPT = 2.9                    # A   (NPT product leg)
ALPHA_ANION_A3 = 3.0           # A^3
AMP, C1, C2 = 0.15, 1.7, 2.3
EV2KJMOL = 96.48533212331002   # kJ/mol per eV (MW lj_pair epsilon unit)

ALPHA_ANION_AU = ALPHA_ANION_A3 / BOHR ** 3   # Bohr^3

HERE = os.path.dirname(os.path.abspath(__file__))


def lattice(d):
    """Return (cations, anions) position lists [A], regression index order."""
    cats, ans = [], []
    idx = 0
    for ix in range(NC):
        for iy in range(NC):
            for iz in range(NC):
                p = [ix * d + AMP * math.sin(C1 * (idx + 1) + C2 * 0.0),
                     iy * d + AMP * math.sin(C1 * (idx + 1) + C2 * 1.0),
                     iz * d + AMP * math.sin(C1 * (idx + 1) + C2 * 2.0)]
                (cats if (ix + iy + iz) % 2 == 0 else ans).append(p)
                idx += 1
    return cats, ans


def write_data(path, box_bohr, blocks, zero_velocities=True):
    """blocks = [(species_name, [xyz in Bohr, ...]), ...] (MW order)."""
    n = sum(len(p) for _, p in blocks)
    with open(path, "w") as fh:
        fh.write("# header\n")
        fh.write("step                         0\n")
        fh.write("num_atoms       %14d\n" % n)
        fh.write("num_electrode_atoms          0\n")
        fh.write("# box\n")
        fh.write("   %.15E %.15E %.15E\n" % (box_bohr, box_bohr, box_bohr))
        fh.write("# coordinates\n")
        for name, pts in blocks:
            for p in pts:
                fh.write("%-4s %23.15E %23.15E %23.15E\n"
                         % (name, p[0], p[1], p[2]))
        if zero_velocities:
            # explicit zero velocities: kinetic energy and kinetic stress
            # vanish, so the pol/nopol difference is purely configurational.
            fh.write("# velocities\n")
            for name, pts in blocks:
                for _ in pts:
                    fh.write("%-4s %23.15E %23.15E %23.15E\n"
                             % (name, 0.0, 0.0, 0.0))


def write_runtime(path, box_bohr, counts, polarizable, rcut_bohr,
                  npt_steps=0, temperature=0.0, lj=None,
                  rtol=1.0e-12, ktol=1.0e-12, dip_tol=1.0e-14):
    lines = []
    lines.append("# MetalWalls twin of ATV regression pim-npt-polarizable-il")
    lines.append("# generated by tools/metalwalls_oracle/inputs/metalwalls/"
                 "pim-npt-polarizable-il/gen_mw_twin.py")
    lines.append("num_steps %d" % npt_steps)
    lines.append("timestep  41.341")          # 1 fs in atomic time units
    lines.append("temperature %.6f" % temperature)
    lines.append("")
    lines.append("num_pbc 3")
    lines.append("box")
    lines.append("  length %.15E %.15E %.15E" % (box_bohr, box_bohr, box_bohr))
    if npt_steps > 0:
        # ATV leg 3: NoseHooverNPT{T=800 K, tau_T=100 fs, P=0, tau_P=500 fs}
        # 100 fs = 4134.1 a.u.; 500 fs = 20670.5 a.u.
        lines.append("")
        lines.append("thermostat")
        lines.append("  chain_length 5")
        lines.append("  relaxation_time 4134.1")
        lines.append("  tolerance 1.0e-15")
        lines.append("  max_iteration 100")
        lines.append("")
        lines.append("barostat")
        lines.append("  pressure 0.0")
        lines.append("  chain_length 5")
        lines.append("  relaxation_time 20670.5")
    lines.append("")
    lines.append("species")
    for name, cnt, q, alpha in counts:
        lines.append("")
        lines.append("  species_type")
        lines.append("    name  %s" % name)
        lines.append("    count %d" % cnt)
        lines.append("    charge point %.15E" % q)
        lines.append("    mass  100.0")
        lines.append("    mobile True")
        if polarizable and alpha > 0.0:
            lines.append("    polarizability %.15E" % alpha)
    if polarizable and any(a > 0.0 for _, _, _, a in counts):
        lines.append("")
        lines.append("  dipoles_minimization cg %.3g 500" % dip_tol)
    lines.append("")
    lines.append("interactions")
    lines.append("  coulomb")
    lines.append("    coulomb_rtol %.6g" % rtol)
    lines.append("    coulomb_rcut %.6f" % rcut_bohr)
    lines.append("    coulomb_ktol %.6g" % ktol)
    if polarizable and any(a > 0.0 for _, _, _, a in counts):
        # MetalWalls allocates tt%b / tt%order / tt%c ONLY inside
        # read_damping_parameters (configuration.F90:3264), and the PIM
        # short-range kernel dereferences them unconditionally
        # (coulomb_sr_pim_3DPBC.inc:514) -> omitting this section segfaults.
        # c = 0 makes the Tang-Toennies charge-dipole damping the identity,
        # i.e. the bare (undamped) charge-dipole tensor.
        lines.append("")
        lines.append("  damping")
        for na, _, _, _ in counts:
            for nb, _, _, _ in counts:
                lines.append("    tt_pair %s %s 1.0 4 0.0" % (na, nb))
    if lj is not None:
        eps_kjmol, sigma_A, rcut_lj_bohr = lj
        lines.append("")
        lines.append("  lennard-jones")
        lines.append("    lj_rcut %.6f" % rcut_lj_bohr)
        for na, _, _, _ in counts:
            for nb, _, _, _ in counts:
                lines.append("    lj_pair %s %s %.9f %.9f"
                             % (na, nb, eps_kjmol, sigma_A))
    lines.append("")
    lines.append("output")
    # Single points dump everything; the 250-step wall-clock twin dumps only
    # the last step, matching the ATV regression (no thermo, timing off).
    every = max(npt_steps, 1)
    lines.append("  default %d" % (0 if npt_steps else 1))
    lines.append("  energies %d Total Kinetic Potential Coulomb Coulomb_lr "
                 "Coulomb_keq0 Coulomb_sr Coulomb_self" % every)
    lines.append("")
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def emit(case, box_bohr, blocks_A, counts, polarizable, rcut_bohr,
         sub=None, **kw):
    d = os.path.join(HERE, case, sub or ("pol" if polarizable else "nopol"))
    os.makedirs(d, exist_ok=True)
    blocks_bohr = [(n, [[c / BOHR for c in p] for p in pts])
                   for n, pts in blocks_A]
    write_data(os.path.join(d, "data.inpt"), box_bohr, blocks_bohr,
               zero_velocities=kw.get("npt_steps", 0) == 0)
    write_runtime(os.path.join(d, "runtime.inpt"), box_bohr, counts,
                  polarizable, rcut_bohr, **kw)
    return d


def main():
    print("BOHR      = %.15g A" % BOHR)
    print("HARTREE   = %.15g eV" % HARTREE)
    print("alpha     = %.15g A^3 = %.15g Bohr^3" % (ALPHA_ANION_A3,
                                                    ALPHA_ANION_AU))

    # ---- lattice64: the exact regression start configuration --------------
    cats, ans = lattice(D_PIN)
    L_A = NC * D_PIN
    L_bohr = L_A / BOHR
    print("lattice64 L = %.15g A = %.15g Bohr, ncat=%d nan=%d"
          % (L_A, L_bohr, len(cats), len(ans)))
    counts = [("Ct", len(cats), +1.0, 0.0),
              ("An", len(ans), -1.0, ALPHA_ANION_AU)]
    blocks = [("Ct", cats), ("An", ans)]
    for pol in (True, False):
        print("  ->", emit("lattice64", L_bohr, blocks, counts, pol,
                           rcut_bohr=0.499 * L_bohr))

    # ---- dimer at growing box: isolated-pair convergence -------------------
    for L_bohr_d in (30.0, 45.0, 60.0, 90.0):
        c = [[0.0, 0.0, 0.0]]
        a = [[D_PIN, 0.0, 0.0]]
        counts_d = [("Ct", 1, +1.0, 0.0), ("An", 1, -1.0, ALPHA_ANION_AU)]
        blocks_d = [("Ct", c), ("An", a)]
        case = "dimer_L%03d" % int(L_bohr_d)
        for pol in (True, False):
            emit(case, L_bohr_d, blocks_d, counts_d, pol,
                 rcut_bohr=0.499 * L_bohr_d)
        print("  -> %s (L = %.3f Bohr = %.4f A)"
              % (case, L_bohr_d, L_bohr_d * BOHR))

    # ---- npt250: wall-clock twin of the regression's NPT product leg -------
    # d = 2.9 A stretched lattice, 250 steps, dt = 1 fs, T = 800 K,
    # tau_T = 100 fs, tau_P = 500 fs, P = 0, LJ(0.01 eV, 3.0 A, rc 4.0 A).
    cats_n, ans_n = lattice(D_NPT)
    Ln_bohr = NC * D_NPT / BOHR
    counts_n = [("Ct", len(cats_n), +1.0, 0.0),
                ("An", len(ans_n), -1.0, ALPHA_ANION_AU)]
    d = emit("npt250", Ln_bohr, [("Ct", cats_n), ("An", ans_n)], counts_n,
             True, rcut_bohr=0.499 * Ln_bohr, sub="run",
             npt_steps=250, temperature=800.0,
             lj=(0.01 * EV2KJMOL, 3.0, 4.0 / BOHR),
             # production-grade Ewald / dipole tolerances (the values the
             # upstream MW NaCl_PIM_NPT example ships) -- a wall-clock twin
             # must not be handicapped by the oracle-grade 1e-12 settings
             # used for the single-point pins above.
             rtol=1.63e-5, ktol=1.0e-7, dip_tol=1.0e-7)
    print("  -> %s (L = %.4f A, 250 NPT steps)" % (d, NC * D_NPT))

    e_iso = -0.5 * 14.399645 * ALPHA_ANION_A3 / D_PIN ** 4
    print("exact isolated-pair E_pol = %.15g eV = %.15g Ha"
          % (e_iso, e_iso / HARTREE))


if __name__ == "__main__":
    main()
