"""Export actual QE captures as data-only C++ pins and reproducible records."""

import argparse
import gzip
import hashlib
import json
import shutil
from pathlib import Path


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--matrix", type=Path, required=True)
    parser.add_argument("--mp-probes", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    args = parser.parse_args()
    matrix, mp = [json.loads(p.read_text()) for p in [args.matrix, args.mp_probes]]
    if matrix["binary_sha256"] != mp["binary_sha256"]:
        raise ValueError("Oracle captures used different binaries")
    args.out.mkdir(parents=True, exist_ok=True)
    records = []
    declarations = []
    for xc in ["LSDA", "PBE"]:
        for smear, width in [("fd", 0.02), ("gaussian", 0.04), ("mp1", 0.04)]:
            source, source_path = (
                (mp, args.mp_probes) if smear == "mp1" else (matrix, args.matrix)
            )
            selected = [
                c
                for c in source["cases"]
                if c["xc"] == xc and c["smearing"] == smear and c["degauss_ry"] == width
            ]
            if len(selected) != 1:
                raise ValueError(
                    "Capture does not contain exactly one declared oracle case"
                )
            item = selected[0]
            if not all(
                item[key]
                for key in [
                    "accepted_external_output",
                    "converged",
                    "spin_nontrivial",
                    "entropy_nontrivial",
                ]
            ):
                raise ValueError(
                    "Unconverged or vacuous oracle cannot qualify the declared case"
                )
            raw = source_path.parent / item["output"]
            inp = raw.parent / "h3.in"
            if sha(raw) != item["output_sha256"] or sha(inp) != item["input_sha256"]:
                raise ValueError("Original oracle input/output changed")
            label = f"{xc.lower()}-{smear}-{width:.2f}"
            out = args.out / "captures" / label
            out.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(inp, out / "h3.in")
            with gzip.open(out / "qe.out.gz", "wb") as stream:
                stream.write(raw.read_bytes())
            value = {
                **item,
                "energy_ha": item["energy_ry"] / 2,
                "source_capture_sha256": sha(source_path),
                "raw_output": str((out / "qe.out.gz").relative_to(args.out)),
                "input": str((out / "h3.in").relative_to(args.out)),
            }
            records.append(value)
            values = ", ".join(format(v, ".17g") for v in item["stress_voigt_ev_ang3"])
            declarations.append(
                f'    {{"{xc}", "{smear}", {width}, {value["energy_ha"]:.17g}, {{{values}}}}}'
            )
    report = {
        "scope": "Actual independent QE7.6 H3 spin-smearing energy and physical stress pins; no native acceptance implied",
        "binary": matrix["binary"],
        "binary_sha256": matrix["binary_sha256"],
        "capture_script": "capture.py",
        "export_script_sha256": sha(__file__),
        "capture_references_sha256": {
            str(p): sha(p) for p in [args.matrix, args.mp_probes]
        },
        "published_potential_source": matrix["published_potential_source"],
        "published_potential_source_sha256": matrix[
            "published_potential_source_sha256"
        ],
        "potential_sha256": matrix["potential_sha256"],
        "predeclared_bounds": matrix["bounds_fixed_before_native_comparison"],
        "stress_convention": matrix["stress_convention"],
        "magnetization_print_precision": "QE prints two decimal places; pins only qualify nonzero magnetization, not an exact moment",
        "cases": records,
    }
    (args.out / "reference.json").write_text(json.dumps(report, indent=2) + "\n")
    header = """// Actual QE7.6 printed energy/stress; generated by export_pins.py.
#pragma once
#include <array>
namespace qe_spin_stress {
struct Pin {
    const char* xc;
    const char* smearing;
    double degauss_ry;
    double energy_ha;
    std::array<double, 6> stress_ev_ang3; // xx,yy,zz,xy,xz,yz; compressive positive.
};
inline constexpr std::array<Pin, 6> pins = {{
"""
    (args.out / "pins.h").write_text(
        header + ",\n".join(declarations) + "\n}};\n} // namespace qe_spin_stress\n"
    )


if __name__ == "__main__":
    main()
