const AM1Parameter* rm1_parameter(int z) noexcept {
    for (const auto& p : kRM1Parameters) {
        if (p.atomic_number == z)
            return &p;
    }
    return nullptr;
}

bool rm1_has_parameter(int z) noexcept { return rm1_parameter(z) != nullptr; }

double rm1_atomic_heat_kcal_mol(int z) {
    // Experimental atomic heats are method-independent tables.
    return am1_atomic_heat_kcal_mol(z);
}

